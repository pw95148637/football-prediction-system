"""Build one judgment record from a final 研判 lean, with every number computed
by project code (sizing, report.build), then validate it. Prints the record as
JSON; `--write` also appends it via judgment.record (main session only).

Used by the main session after the judgment-synthesis architecture has run
through the Agent tool (ops/workflow_harness.mjs generates the prompts).

usage: python ops/assemble_judgment.py <brief.json> <final_lean.json> <meta.json>
           [--blind <stage1_lean.json>] [--write]
meta.json: {"depth": "full|light", "escalation_reason": str|null,
            "critique_verdicts": {...}, "revised": bool,
            "model": str, "reviewer_models": [...],
            "recorder_note"?: str, "bet_candidate"?: bool}

--blind: the stage-1 (price-blind) lean. The record then carries
blind_probs_90, and a final probability that differs from it is refused
unless the final lean's post_price_changes names the non-price information
that moved it (the same check the workflow applies).
"""
import json
import sys

from football_ai.competitions.epl_2026_27 import BIAS_PATTERN_PP, CONFIG, ERA
from football_ai.decision import judgment, sizing
from football_ai.decision.report import build

brief_path, lean_path, meta_path = sys.argv[1:4]
write = "--write" in sys.argv
blind = (json.load(open(sys.argv[sys.argv.index("--blind") + 1], encoding="utf-8"))
         if "--blind" in sys.argv else None)
lean = json.load(open(lean_path, encoding="utf-8"))
meta = json.load(open(meta_path, encoding="utf-8"))
mid = lean["match_id"]
m = next(x for x in json.load(open(brief_path, encoding="utf-8"))["args"]["matches"]
         if x["mid"] == mid)

# The entry price is the last snapshot before the close. A closing snapshot is
# the yardstick the judgment is scored against, never its entry: once one is
# stored, build() would price the record at the close, so it is hidden here.
from football_ai.store import io as _io
_read = _io.read
_io.read = lambda kind, *a, **k: [r for r in _read(kind, *a, **k)
                                  if not (kind == "odds" and (r.get("data") or {}).get("closing"))]
try:
    b = build(mid, mechanism=None, config=CONFIG)
finally:
    _io.read = _read
one = next(x for x in b["markets"] if x.get("market") == "1x2")
d = lean["direction"]
p = lean["judgment_probs_90"][d]
odds = one["odds"][d]
gap_pp = b["gate"]["gap_used_pp"]  # J's largest 1x2 gap vs market (J=M here)

grade = lean["mechanism_grade"]
mtype = lean.get("mechanism_type")
prec_n, prec_hit = (sizing.precedent_stats(mtype, era=ERA)
                    if (grade in ("verified", "graded") and mtype) else (0, None))
# STAKING 2.2: the bias band was measured on M only, so J's gap decides;
# the lean's own gap is recorded for information and never widens it.
fair = one["market_fair"]
lean_gap_pp = 100 * max(abs(lean["judgment_probs_90"][k] - fair[k]) for k in fair)
bias_gap_pp = abs(gap_pp)
lam = sizing.confidence_lambda(
    p, grade, mech_score=lean.get("mechanism_score"),
    in_known_bias_pattern=sizing.gap_bias_pattern(bias_gap_pp, BIAS_PATTERN_PP),
    precedent_n=prec_n, precedent_hit_rate=prec_hit)
f_star = sizing.kelly_fraction(p, odds)

rec = {
    "match_id": mid,
    "judgment_probs_90": lean["judgment_probs_90"],
    "direction": d,
    "prob": p,
    "confidence": lean["confidence"],
    "j_status": m["j_status"],
    "j_probs_90": m["j_probs"],
    "diverges_from_j": lean["diverges_from_j"],
    "divergence_note": lean["divergence_note"],
    "capabilities_used": lean["capabilities_used"],
    "basis": lean["basis"],
    "mechanism_grade": grade,
    "mechanism_type": mtype,
    "market_error_mechanism": lean["market_error_mechanism"],
    "abstention": lean["abstention"],
    "lambda": lam["lambda"],
    "lambda_components": lam["components"],
    "f_star": f_star,
    "kappa": sizing.KAPPA,
    "entry_price": {"selection": d, "book": one["best_book"][d], "decimal_odds": odds,
                    "at": one["at"]},
    "market_devigged": one["market_fair"],
    "ev_at_entry": sizing.ev(p, odds),
    "gap_used_pp": gap_pp,
    "lean_gap_pp": lean_gap_pp,
    "bias_gap_pp": bias_gap_pp,
    "bias_gap_rule": "|J gap| vs BIAS_PATTERN_PP (STAKING 2.2: band measured on M only)",
    "outcome": None,
    "commands_run": lean.get("commands_run"),
    "honest_gaps": lean.get("honest_gaps"),
    "review_depth": meta["depth"],
    "escalation_reason": meta.get("escalation_reason"),
    "critique_verdicts": meta.get("critique_verdicts"),
    "revised_after_critique": meta.get("revised"),
    "workflow": "judgment-synthesis (Agent tool, prompts generated by the workflow's own code)",
    "model": meta["model"],
    "reviewer_models": meta["reviewer_models"],
}
if blind is not None:
    moved = any(abs(lean["judgment_probs_90"][k] - blind["judgment_probs_90"][k]) > 1e-6
                for k in ("home", "draw", "away"))
    why = str(lean.get("post_price_changes") or "").strip()
    if moved and why in ("", "無"):
        sys.exit("refused: the probability moved after the price with no non-price "
                 "reason in post_price_changes")
    rec["blind_probs_90"] = blind["judgment_probs_90"]
    rec["post_price_changes"] = why or "無"
if meta.get("recorder_note"):
    rec["recorder_note"] = meta["recorder_note"]
if grade == "graded" and lean.get("mechanism_score") is not None:
    rec["mechanism_score"] = lean["mechanism_score"]
# A stake is recorded only for a gate-cleared bet; otherwise the abstention
# carries the record and lambda*f_star still ranks the lean.
if meta.get("bet_candidate"):
    rec["stake_frac"] = sizing.stake_fraction(lam["lambda"], f_star)

errors = judgment.validate_record(rec)
print(json.dumps({"errors": errors, "rank_key": judgment.rank_key(rec),
                  "lambda": rec["lambda"], "components": rec["lambda_components"],
                  "f_star": f_star, "ev_at_entry": rec["ev_at_entry"],
                  "entry_price": rec["entry_price"], "gap_used_pp": gap_pp,
                  "lean_gap_pp": lean_gap_pp},
                 ensure_ascii=False, indent=1))
if write:
    if errors:
        sys.exit("not written: validation errors above")
    out = judgment.record(rec, era=ERA)
    print("written:", out.get("ts") if isinstance(out, dict) else out)
